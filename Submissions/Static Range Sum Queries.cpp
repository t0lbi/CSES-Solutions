vector<int> segtree;
int seg_tree_len;
enum segment_tree_mode{
    sumq,
    minq,
    maxq
};
void build(segment_tree_mode segtree_mode){
    int os=segtree.size();
    segtree.resize(1ll<<((int)ceil(log2(segtree.size()))));
    seg_tree_len=segtree.size();
    for (int i = os;i<segtree.size();i++){
        if (segtree_mode==sumq){
            segtree[i]=0;
        }
        else if (segtree_mode==minq){
            segtree[i]=LONG_LONG_MAX;
        }
        else if (segtree_mode==maxq){
            segtree[i]=LONG_LONG_MIN;
        }
    }
    os=segtree.size();
    segtree.resize(os*2-1);
    for (int i = 1;i<=os;i++){
        segtree[segtree.size()-i]=segtree[os-i];
    }
    for (int i = segtree.size()-1;i>=0;i--){
        if (i*2+2>=segtree.size())continue;
        if (segtree_mode==sumq){
            segtree[i]=segtree[i*2+1]+segtree[i*2+2];
        }
        else if (segtree_mode==minq){
            segtree[i]=min(segtree[i*2+1],segtree[i*2+2]);
        }
        else if (segtree_mode==maxq){
            segtree[i]=max(segtree[i*2+1],segtree[i*2+2]);
        }
    }
}
void update(int node,segment_tree_mode segtree_mode){
    if (node*2+2<segtree.size()){
        if (segtree_mode==sumq){
            segtree[node]=segtree[node*2+1]+segtree[node*2+2];
        }
        else if (segtree_mode==minq){
            segtree[node]=min(segtree[node*2+1],segtree[node*2+2]);
        }
        else if (segtree_mode==maxq){
            segtree[node]=max(segtree[node*2+1],segtree[node*2+2]);
        }
    }
    if (node==0)return;
    update((node-1)/2,segtree_mode);
}
int query(int tarl,int tarr,segment_tree_mode segtree_mode,int l=0,int r=seg_tree_len-1,int node=0){
    if (l>tarr || r<tarl) {
        if (segtree_mode==minq){
            return LONG_LONG_MAX;
        }
        else if (segtree_mode==maxq){
            return LONG_LONG_MIN;
        }
        else if (segtree_mode==sumq){
            return 0;
        }
    }
    if (l>=tarl && r<=tarr){
        return segtree[node];
    }
    int mid=l+(r-l)/2;
    int lchild=query(tarl,tarr,segtree_mode,l,mid,node*2+1);
    int rchild=query(tarl,tarr,segtree_mode,mid+1,r,node*2+2);
    if (segtree_mode==minq){
        return min(lchild,rchild);
    }
    if (segtree_mode==maxq){
        return max(lchild,rchild);
    }
    return lchild+rchild;
}
