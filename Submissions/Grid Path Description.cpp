int dfs(int x,int y,vector<int> vis,int sum){
	if (printmode) cerr<<x<<" "<<y<<endl;
	vis[x]|=tol(y);
	sum++;
	if ((x==0 && y==6) || sum == 49){
		return (x==0 && y==6 && sum==49);
	}
	bool gr=true,gl=true,gu=true,gd=true;
	bool ru=true,lu=true,rd=true,ld=true;
	if (y==0 || (vis[x]&tol(y-1))) gu=false;
	if (y==6 || (vis[x]&tol(y+1))) gd=false;
	if (x==6 || (vis[x+1]&tol(y))) gr=false;
	if (x==0 || (vis[x-1]&tol(y))) gl=false;
	if (x==0 || y==0 || (vis[x-1]&tol(y-1))) lu=false;
	if (x==0 || y==6 || (vis[x-1]&tol(y+1))) ld=false;
    if (x==6 || y==0 || (vis[x+1]&tol(y-1))) ru=false;
	if (x==6 || y==6 || (vis[x+1]&tol(y+1))) rd=false;
	if (gu && gr && !ru) return 0;
	if (gu && gl && !lu) return 0;
	if (gd && gr && !rd) return 0;
	if (gd && gl && !ld) return 0;
	if (!gu && !gd){
		if (gl&&gr) {if(printmode)cerr<<"basarisiz"<<endl;return 0;}
	}
	if (!gr && !gl){
		if (gu&&gd) {if(printmode)cerr<<"basarisiz"<<endl;return 0;}
	}
	if (str[sum-1]=='R') {if (gr) return dfs(x+1,y,vis,sum); else return 0;}
	if (str[sum-1]=='L') {if (gl) return dfs(x-1,y,vis,sum); else return 0;}
	if (str[sum-1]=='U') {if (gu) return dfs(x,y-1,vis,sum); else return 0;}
	if (str[sum-1]=='D') {if (gd) return dfs(x,y+1,vis,sum); else return 0;}
	int retval=0;
	if (gr) retval+=dfs(x+1,y,vis,sum);
	if (gl) retval+=dfs(x-1,y,vis,sum);
	if (gu) retval+=dfs(x,y-1,vis,sum);
	if (gd) retval+=dfs(x,y+1,vis,sum);
	return retval;
}
